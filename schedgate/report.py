from __future__ import annotations

from html import escape

from .model import Report


def as_text(report: Report) -> str:
    lines = [report.title, "=" * len(report.title), ""]
    if report.files:
        lines.append("Files")
        lines.extend(f"  - {path}" for path in report.files)
        lines.append("")
    if report.threads:
        lines.append("Threads")
        for thread in report.threads:
            lines.append(
                f"  - {thread.name}: {thread.policy} pri={thread.priority} "
                f"period={thread.period_ns}ns wcet={thread.wcet_ns}ns"
            )
        if report.schedulable is not None:
            flag = "SCHEDULABLE" if report.schedulable else "NOT SCHEDULABLE"
            lines.append(f"  utilization={report.utilization:.3f} liu_layland={report.liu_layland_bound:.3f} => {flag}")
        lines.append("")
    if not report.findings:
        lines.append("No findings.")
        return "\n".join(lines) + "\n"
    lines.append("Findings")
    for finding in report.findings:
        loc = f" ({finding.source})" if finding.source else ""
        lines.append(f"  [{finding.severity.upper()}] {finding.code}: {finding.message}{loc}")
    return "\n".join(lines) + "\n"


def as_html(report: Report) -> str:
    rows = []
    for finding in report.findings:
        rows.append(
            "<tr>"
            f"<td>{escape(finding.severity)}</td>"
            f"<td><code>{escape(finding.code)}</code></td>"
            f"<td>{escape(finding.message)}</td>"
            f"<td><code>{escape(finding.source)}</code></td>"
            "</tr>"
        )
    thread_rows = []
    for thread in report.threads:
        thread_rows.append(
            "<tr>"
            f"<td>{escape(thread.name)}</td>"
            f"<td><code>{escape(thread.policy)}</code></td>"
            f"<td>{thread.priority}</td>"
            f"<td>{thread.period_ns}</td>"
            f"<td>{thread.wcet_ns}</td>"
            "</tr>"
        )
    sched = "n/a" if report.schedulable is None else ("yes" if report.schedulable else "no")
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>{escape(report.title)}</title>
  <style>
    body {{ font-family: ui-sans-serif, Helvetica, Arial, sans-serif; margin: 2rem; color: #102026; background: #f4f1ea; }}
    h1 {{ font-size: 1.4rem; }}
    table {{ border-collapse: collapse; width: 100%; background: white; }}
    th, td {{ border: 1px solid #d5d0c6; padding: 0.45rem 0.6rem; text-align: left; vertical-align: top; }}
    th {{ background: #ece7dc; }}
    .error {{ color: #8b1e1e; }}
    .warning {{ color: #8a5a12; }}
    .note {{ color: #1d4a3a; }}
    code {{ font-size: 0.86em; }}
  </style>
</head>
<body>
  <h1>{escape(report.title)}</h1>
  <p>Periodic utilization: {report.utilization:.3f}. Liu-Layland bound: {report.liu_layland_bound:.3f}. Rate-monotonic schedulable: {sched}.</p>
  <h2>Threads</h2>
  <table>
    <tr><th>Name</th><th>Policy</th><th>Priority</th><th>Period (ns)</th><th>WCET (ns)</th></tr>
    {''.join(thread_rows) or '<tr><td colspan="5">No thread spec.</td></tr>'}
  </table>
  <h2>Findings</h2>
  <table>
    <tr><th>Severity</th><th>Code</th><th>Message</th><th>Source</th></tr>
    {''.join(rows) or '<tr><td colspan="4">No findings.</td></tr>'}
  </table>
  <p>Generated by schedgate, a host-side QNX 8.0 readiness tool. Built by Luis Alfredo Salazar Courtois with assistance from an AI system under his direction.</p>
</body>
</html>
"""
